#!/usr/bin/env node
// One-time (re-runnable, deterministic) generator: wraps the 79 legacy
// supabase/migrations/*.sql files as dbmate migrations under db/migrations/ and
// writes scripts/db/mark-applied.sql. The originals are NEVER modified — they
// are the frozen history; new migrations are written directly with `dbmate new`.
//
//   node scripts/db/gen-legacy-dbmate-migrations.mjs          # (re)generate
//   node scripts/db/gen-legacy-dbmate-migrations.mjs --check  # exit 1 if out of date
//
// Version scheme: 20000101 + 6-digit sequence (lexicographic order of the
// original files, the order production ran them in) → 20000101000001 … 000079.
// Files with their own BEGIN/COMMIT (up or down) run with `transaction:false`,
// exactly as they did under psql (dbmate wraps everything else in one transaction).
// A matching NNN_name.down.sql becomes the migrate:down section.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(ROOT, 'supabase', 'migrations');
const OUT = join(ROOT, 'db', 'migrations');
const MARK = join(ROOT, 'scripts', 'db', 'mark-applied.sql');
const check = process.argv.includes('--check');

const ups = readdirSync(SRC)
  .filter((f) => f.endsWith('.sql') && !f.endsWith('.down.sql'))
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)); // byte order, like LC_ALL=C sort

const hasTx = (sql) => /^\s*(begin|commit|start\s+transaction)\s*;/im.test(sql);

const outputs = new Map();
const versions = [];
ups.forEach((file, i) => {
  const base = file.replace(/\.sql$/, '');
  const version = `20000101${String(i + 1).padStart(6, '0')}`;
  const up = readFileSync(join(SRC, file), 'utf8');
  const downPath = join(SRC, `${base}.down.sql`);
  const down = existsSync(downPath) ? readFileSync(downPath, 'utf8') : null;
  const txFlag = hasTx(up) ? ' transaction:false' : '';
  const downTxFlag = down && hasTx(down) ? ' transaction:false' : '';
  const body =
    `-- Generated by scripts/db/gen-legacy-dbmate-migrations.mjs from\n` +
    `-- supabase/migrations/${file} — do not edit; edit nothing, history is frozen.\n` +
    `-- migrate:up${txFlag}\n` +
    up.replace(/\s*$/, '\n') +
    `\n-- migrate:down${downTxFlag}\n` +
    (down ? down.replace(/\s*$/, '\n') : `-- no down migration was written for legacy ${base}\n`);
  outputs.set(`${version}_${base}.sql`, body);
  versions.push(version);
});

const mark =
  `-- scripts/db/mark-applied.sql — generated by scripts/db/gen-legacy-dbmate-migrations.mjs\n` +
  `--\n` +
  `-- Marks the ${versions.length} legacy migrations (supabase/migrations/001…078, already\n` +
  `-- applied to production by psql) as applied in dbmate's table, so that\n` +
  `-- \`dbmate status\` shows them as done and \`dbmate up\` only runs NEW files.\n` +
  `--\n` +
  `-- NOT RUN IN PRODUCTION YET. Procedure (docs/migrations.md):\n` +
  `--   1. dump the production schema and diff it against db/schema.sql\n` +
  `--   2. only if the diff is empty:\n` +
  `--      docker exec -i supabase-db psql -U postgres -d proj_billing -v ON_ERROR_STOP=1 < scripts/db/mark-applied.sql\n` +
  `-- Idempotent: re-running inserts nothing new.\n` +
  `\n` +
  `CREATE TABLE IF NOT EXISTS public.schema_migrations (version character varying NOT NULL PRIMARY KEY);\n` +
  `\n` +
  `INSERT INTO public.schema_migrations (version) VALUES\n` +
  versions.map((v, i) => `  ('${v}')${i === versions.length - 1 ? '' : ','}  -- ${ups[i]}`).join('\n') +
  `\nON CONFLICT (version) DO NOTHING;\n`;
outputs.set(MARK, mark);

let stale = 0;
for (const [name, body] of outputs) {
  const path = name.startsWith('/') ? name : join(OUT, name);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === body) continue;
  stale++;
  if (!check) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
  }
}
// Stray files in db/migrations that are not legacy wrappers are fine (new
// dbmate migrations); stale wrappers with an old version scheme are not.
const strays = readdirSync(OUT).filter((f) => f.startsWith('20000101') && !outputs.has(f));
if (check) {
  if (stale || strays.length) {
    console.error(`legacy dbmate wrappers out of date: ${stale} file(s) differ, ${strays.length} stray`);
    process.exit(1);
  }
  console.log(`legacy dbmate wrappers in sync (${versions.length})`);
} else {
  console.log(`wrote ${stale} file(s); ${versions.length} legacy migrations wrapped; ${strays.length} stray`);
  strays.forEach((f) => console.log('  stray (delete by hand):', f));
}
